#!/usr/bin/env python3
"""Aggregate and format head-to-head CPU efficiency measurements (efficiency_1118).

Step 1 (--collect RAW): reads all 520 train/t1, train/t8, and latency JSONs from RAW
   (e.g. /home/s4il0r/nca_e_logs/efficiency_1118) and writes
   stage0/stage0_results/efficiency_1118/efficiency_summary.json.
Step 2 (default): reads efficiency_summary.json and writes
   paper/generated/tab_efficiency_1118.tex and
   paper/generated/numbers_efficiency_1118.tex.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT_DIR = REPO / "stage0" / "stage0_results" / "efficiency_1118"
SUMMARY_PATH = OUT_DIR / "efficiency_summary.json"
GEN_DIR = REPO / "paper" / "generated"

BENCHES = [
    ("curated", "Hermes", "Her"),
    ("bfcl_e1v2", "BFCL", "Bfcl"),
    ("toolbench", "ToolBench", "Tb"),
    ("apibank", "API-Bank", "Ab"),
]
MODELS = [
    ("logreg", "Lr", "Logistic regression"),
    ("rf", "Rf", "Random Forest"),
    ("hgb", "Hgb", "HistGradientBoosting"),
    ("rf_cell", "Rfp", "Random Forest$^\\ast$"),
    ("hgb_cell", "Hgbp", "HistGradientBoosting$^\\ast$"),
    ("knn", "Knn", "$k$-NN retrieval"),
    ("mlp", "Mlp", "MLP"),
    ("transformer", "Tf", "Transformer"),
    ("gnn_untied", "Gnn", "GNN (untied steps)"),
    ("gnca_chain", "Chain", "GNCA chain"),
    ("gnca_star", "Star", "GNCA star"),
    ("gnca_learned", "Meta", "GNCA learned"),
    ("gnca_tree", "Gnca", "GNCA tree (primary)"),
]
GROUPS = [
    ["logreg", "rf", "hgb", "rf_cell", "hgb_cell"],
    ["knn", "mlp", "transformer", "gnn_untied"],
    ["gnca_chain", "gnca_star", "gnca_learned", "gnca_tree"],
]
SEEDS = [0, 1, 2, 3, 4]


def collect(raw: Path) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    summary = {
        "source": "engine ~/nca_e_logs/efficiency_1118 (stage0/efficiency/run_efficiency_1118.py)",
        "seeds": SEEDS,
        "benchmarks": {},
    }
    hardware = None
    for b, *_ in BENCHES:
        b_out = {}
        for m, *_ in MODELS:
            t1 = [json.loads((raw / "train" / "t1" / b / m / f"seed{s}.json").read_text()) for s in SEEDS]
            t8 = [json.loads((raw / "train" / "t8" / b / m / f"seed{s}.json").read_text()) for s in SEEDS]
            lat = [json.loads((raw / "latency" / b / m / f"seed{s}.json").read_text()) for s in SEEDS]
            if hardware is None:
                hardware = t8[0].get("hardware", {})
            b_out[m] = {
                "n_params": t1[0].get("n_params"),
                "size_kb": round(statistics.median(x["size_bytes"] for x in t1) / 1024.0, 1),
                "train_t1_s": round(statistics.median(x["train_s"] for x in t1), 2),
                "train_t8_s": round(statistics.median(x["train_s"] for x in t8), 2),
                "peak_rss_mb_t1": round(statistics.median(x["peak_rss_mb"] for x in t1), 1),
                "peak_rss_mb_t8": round(statistics.median(x["peak_rss_mb"] for x in t8), 1),
                "featurise_ms": round(statistics.median(x["featurise_ms"]["median"] for x in lat), 3),
                "predict_ms": round(statistics.median(x["predict_ms"]["median"] for x in lat), 3),
                "predict_p95_ms": round(statistics.median(x["predict_ms"]["p95"] for x in lat), 3),
                "total_ms": round(statistics.median(x["total_ms"]["median"] for x in lat), 3),
                "test_top1_med": round(statistics.median(x["test_top1"] for x in t1), 2),
                "published_test_top1": t1[0].get("published_test_top1"),
            }
        summary["benchmarks"][b] = b_out
    summary["hardware"] = {
        "cpu": hardware.get("cpu", "AMD Ryzen 9 7950X 16-Core Processor"),
        "torch": hardware.get("torch", ""),
        "sklearn": hardware.get("sklearn", ""),
    }
    SUMMARY_PATH.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"Wrote {SUMMARY_PATH}")


def fmt_params(n: int | None) -> str:
    if n is None:
        return "--"
    if n >= 1000:
        return f"{n / 1000.0:.1f}k"
    return str(n)


def fmt_size(kb: float) -> str:
    if kb >= 1024.0:
        return f"{kb / 1024.0:.1f}\\,MB"
    return f"{int(round(kb))}\\,kB"


def build_tex() -> None:
    summary = json.loads(SUMMARY_PATH.read_text())
    bm = summary["benchmarks"]
    GEN_DIR.mkdir(parents=True, exist_ok=True)

    # Table
    lines = [
        "% AUTO-GENERATED by scripts/build_efficiency_1118.py",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{@{}lrrrrrrrrrr@{}}",
        "\\toprule",
        "& \\multicolumn{2}{c}{Hermes size} & \\multicolumn{2}{c}{Hermes} & \\multicolumn{2}{c}{BFCL} & \\multicolumn{2}{c}{ToolBench} & \\multicolumn{2}{c}{API-Bank} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\\cmidrule(lr){10-11}",
        "Model & Params & Serial. & Train$_{8}$ (s) & Infer (ms) & Train$_{8}$ (s) & Infer (ms) & Train$_{8}$ (s) & Infer (ms) & Train$_{8}$ (s) & Infer (ms) \\\\",
        "\\midrule",
    ]
    disp = {m: d for m, _, d in MODELS}
    for gi, grp in enumerate(GROUPS):
        if gi > 0:
            lines.append("\\midrule")
        for m in grp:
            her = bm["curated"][m]
            cells = [
                disp[m],
                fmt_params(her["n_params"]),
                fmt_size(her["size_kb"]),
            ]
            for b, *_ in BENCHES:
                rec = bm[b][m]
                cells.append(f"{rec['train_t8_s']:.2f}" if rec["train_t8_s"] < 10 else f"{rec['train_t8_s']:.1f}")
                cells.append(f"{rec['predict_ms']:.3f}" if rec["predict_ms"] < 1 else f"{rec['predict_ms']:.2f}")
            lines.append(" & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}}"])
    tab_path = GEN_DIR / "tab_efficiency_1118.tex"
    tab_path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {tab_path}")

    # Macros
    gnca_params = [bm[b]["gnca_tree"]["n_params"] for b, *_ in BENCHES]
    gnca_pred = [bm[b]["gnca_tree"]["predict_ms"] for b, *_ in BENCHES]
    gnca_t8 = [bm[b]["gnca_tree"]["train_t8_s"] for b, *_ in BENCHES]
    gnca_t1 = [bm[b]["gnca_tree"]["train_t1_s"] for b, *_ in BENCHES]
    hgb_pred = [bm[b]["hgb"]["predict_ms"] for b, *_ in BENCHES]
    rf_pred = [bm[b]["rf"]["predict_ms"] for b, *_ in BENCHES]
    her_rf_kb = bm["curated"]["rf"]["size_kb"]
    her_hgb_kb = bm["curated"]["hgb"]["size_kb"]
    gnca_kb = [bm["curated"][m]["size_kb"] for m in ("gnca_chain", "gnca_star", "gnca_learned", "gnca_tree")]
    macros = [
        "% AUTO-GENERATED by scripts/build_efficiency_1118.py",
        f"\\newcommand{{\\numEffGncaParamsLo}}{{{min(gnca_params) / 1000.0:.1f}k}}",
        f"\\newcommand{{\\numEffGncaParamsHi}}{{{max(gnca_params) / 1000.0:.1f}k}}",
        f"\\newcommand{{\\numEffGncaPredLo}}{{{min(gnca_pred):.2f}}}",
        f"\\newcommand{{\\numEffGncaPredHi}}{{{max(gnca_pred):.2f}}}",
        f"\\newcommand{{\\numEffGncaTrainEightLo}}{{{min(gnca_t8):.1f}}}",
        f"\\newcommand{{\\numEffGncaTrainEightHi}}{{{max(gnca_t8):.1f}}}",
        f"\\newcommand{{\\numEffGncaTrainOneLo}}{{{min(gnca_t1):.1f}}}",
        f"\\newcommand{{\\numEffGncaTrainOneHi}}{{{max(gnca_t1):.1f}}}",
        f"\\newcommand{{\\numEffHgbPredLo}}{{{min(hgb_pred):.2f}}}",
        f"\\newcommand{{\\numEffHgbPredHi}}{{{max(hgb_pred):.2f}}}",
        f"\\newcommand{{\\numEffRfPredLo}}{{{min(rf_pred):.2f}}}",
        f"\\newcommand{{\\numEffRfPredHi}}{{{max(rf_pred):.2f}}}",
        f"\\newcommand{{\\numEffRfSizeHerm}}{{{her_rf_kb / 1024.0:.1f}}}",
        f"\\newcommand{{\\numEffHgbSizeHerm}}{{{her_hgb_kb / 1024.0:.1f}}}",
        f"\\newcommand{{\\numEffGncaKbLo}}{{{int(round(min(gnca_kb)))}}}",
        f"\\newcommand{{\\numEffGncaKbHi}}{{{int(round(max(gnca_kb)))}}}",
    ]
    num_path = GEN_DIR / "numbers_efficiency_1118.tex"
    num_path.write_text("\n".join(macros) + "\n")
    print(f"Wrote {num_path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--collect", type=Path, default=None, help="Raw efficiency_1118 output directory on engine")
    args = ap.parse_args()
    if args.collect is not None:
        collect(args.collect)
    build_tex()


if __name__ == "__main__":
    main()
