#!/usr/bin/env python3
"""Recurrence-depth (K) sweep of the tuned tree GNCA: collect, statistics, table and macros.

Step 1 (--collect RAW): compact the engine output of stage0/run_ksweep_1124.py (RAW/<bench>/K<k>/seed<s>.{json,npz})
   into stage0/stage0_results/ksweep_1124/{ksweep_summary.json, ksweep_correct.npz} (per-turn test correctness only).
Step 2 (default): paper/generated/{tab_ksweep_1124.tex, numbers_ksweep_1124.tex} and ksweep_1124/stats_ksweep.json.
Every comparison is made inside the sweep: each K against the re-run of the benchmark's selected K (same code path,
same device). Statistics as in build_rigour_tables_1110.py: paired bootstrap over test turns with seeds kept
together (10,000 resamples), Holm over all (benchmark, K) pairs, DerSimonian-Laird pooling over benchmarks.
"""
from __future__ import annotations
import json, sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_review_tables_1110 import cluster_boot, holm, dersimonian_laird  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "stage0" / "stage0_results"; KD = RES / "ksweep_1124"; RG = RES / "rigour_1110"; GEN = REPO / "paper" / "generated"
BENCH = [("curated", "Hermes", "Her"), ("bfcl_e1v2", "BFCL", "Bfcl"), ("toolbench", "ToolBench", "Tb"), ("apibank", "API-Bank", "Ab")]
SEEDS = [0, 1, 2, 3, 4]
WORD = {1: "One", 2: "Two", 4: "Four", 6: "Six", 8: "Eight", 16: "Sixteen"}


def collect(raw: Path):
    KD.mkdir(parents=True, exist_ok=True)
    summ = {"source": "engine /mnt/homelab-external/paper-gap-1124/nca_ksweep (stage0/run_ksweep_1124.py)", "seeds": SEEDS, "benchmarks": {}}
    arr = {}
    for b, *_ in BENCH:
        ks = sorted(int(p.name[1:]) for p in (raw / b).iterdir() if p.is_dir() and p.name.startswith("K"))
        sb = {}
        for k in ks:
            fd = raw / b / f"K{k}"
            recs = [json.loads((fd / f"seed{s}.json").read_text()) for s in SEEDS]
            arr[f"{b}/K{k}"] = np.stack([np.load(fd / f"seed{s}.npz")["test_correct"] for s in SEEDS])
            sb[f"K{k}"] = [{x: r[x] for x in ("K", "K_selected", "seed", "val_top1", "test_top1", "n_params", "wall_s", "device")} for r in recs]
        sb["config"] = recs[0]["config"]; sb["selected_trial"] = recs[0]["selected_trial"]
        summ["benchmarks"][b] = sb
    np.savez_compressed(KD / "ksweep_correct.npz", **arr)
    (KD / "ksweep_summary.json").write_text(json.dumps(summ, indent=1) + "\n")
    print("collected", len(arr), "cells")


def main():
    S = json.loads((KD / "ksweep_summary.json").read_text()); Z = np.load(KD / "ksweep_correct.npz")
    R = np.load(RG / "per_turn_rigour.npz")
    M = {}; put = M.__setitem__
    sel = {b: int(S["benchmarks"][b]["config"]["K"]) for b, *_ in BENCH}
    Ks = sorted({int(k.split("/K")[1]) for k in Z.files})
    acc = {b: {k: (float(100 * Z[f"{b}/K{k}"].mean()), float(np.std(100 * Z[f"{b}/K{k}"].mean(1), ddof=1))) for k in Ks if f"{b}/K{k}" in Z.files} for b, *_ in BENCH}
    pairs = {f"{b}/K{k}": cluster_boot(Z[f"{b}/K{k}"], Z[f"{b}/K{sel[b]}"]) for b, *_ in BENCH for k in Ks if k != sel[b] and f"{b}/K{k}" in Z.files}
    for key, p in zip(pairs, holm([v["p"] for v in pairs.values()])):
        pairs[key]["p_holm"] = p
    pooled = {}
    for k in Ks:
        bs = [b for b, *_ in BENCH if f"{b}/K{k}" in pairs]
        if len(bs) >= 2:
            pooled[k] = dersimonian_laird([pairs[f"{b}/K{k}"]["diff_pp"] for b in bs], [pairs[f"{b}/K{k}"]["se_pp"] for b in bs]); pooled[k]["benchmarks"] = bs
    repro = {b: cluster_boot(Z[f"{b}/K{sel[b]}"], R[f"{b}/gnca_tree/test_correct"]) for b, *_ in BENCH}
    st = {"selected_K": sel, "accuracy_mean_sd": acc, "paired_vs_selected": pairs, "pooled_vs_selected": pooled,
          "rerun_selected_vs_rigour_final": repro, "n_pairs": len(pairs)}
    (KD / "stats_ksweep.json").write_text(json.dumps(st, indent=1, default=float) + "\n")

    sig = [x for x in pairs.values() if x["p_holm"] < 0.05]
    put("KswNPairs", str(len(pairs))); put("KswNSig", str(len(sig)))
    put("KswNSigNeg", str(sum(x["diff_pp"] < 0 for x in sig))); put("KswNSigPos", str(sum(x["diff_pp"] > 0 for x in sig)))
    for k, p in pooled.items():
        w = WORD.get(k, str(k))
        put(f"KswPool{w}", f"{p['estimate_pp']:+.2f}"); put(f"KswPool{w}Lo", f"{p['ci95'][0]:+.2f}"); put(f"KswPool{w}Hi", f"{p['ci95'][1]:+.2f}")
    tb1 = pairs["toolbench/K1"]
    put("KswTbOneD", f"{tb1['diff_pp']:+.2f}"); put("KswTbOneLo", f"{tb1['ci95'][0]:+.2f}"); put("KswTbOneHi", f"{tb1['ci95'][1]:+.2f}")
    put("KswTbOneP", f"{tb1['p_holm']:.3f}")
    put("KswMaxAbsRepro", f"{max(abs(v['diff_pp']) for v in repro.values()):.2f}")
    put("KswNReproSig", str(sum(v["p"] < 0.05 for v in repro.values())))
    lines = ["% AUTO-GENERATED by scripts/build_ksweep_1124.py -- do not edit by hand"] + [f"\\newcommand{{\\num{k}}}{{{v}}}" for k, v in M.items()]
    (GEN / "numbers_ksweep_1124.tex").write_text("\n".join(lines) + "\n")

    mark = lambda p: "$^{\\ast}$" if p < 0.05 else ""
    t = ["% AUTO-GENERATED by scripts/build_ksweep_1124.py", r"\begin{tabular}{@{}r" + "r" * len(BENCH) + r"r@{}}", r"\toprule",
         "$K$ & " + " & ".join(n for _, n, _ in BENCH) + r" & Pooled $\Delta$ [95\% CI] \\", r"\midrule"]
    for k in Ks:
        cells = []
        for b, *_ in BENCH:
            if k not in acc[b]:
                cells.append("--"); continue
            m, sd = acc[b][k]; c = f"{m:.2f}\\,$\\pm$\\,{sd:.2f}"
            if k == sel[b]:
                c = r"\textbf{" + c + "}"
            else:
                c += mark(pairs[f"{b}/K{k}"]["p_holm"])
            cells.append(c)
        p = pooled.get(k); pool = f"{p['estimate_pp']:+.2f} [{p['ci95'][0]:+.2f}, {p['ci95'][1]:+.2f}]" if p else "--"
        t.append(f"{k} & " + " & ".join(cells) + f" & {pool} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (GEN / "tab_ksweep_1124.tex").write_text("\n".join(t) + "\n")
    print("\n".join(t)); print("\n".join(lines))
    for b, v in repro.items():
        print("repro", b, round(v["diff_pp"], 2), [round(x, 2) for x in v["ci95"]], round(v["p"], 3))


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--collect":
        collect(Path(sys.argv[2]))
    main()
