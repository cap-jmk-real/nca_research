#!/usr/bin/env python3
"""Extra macros, the factorial table and two figures for the concise v7.6 revision (2026-11-10).

Every value is read from a result file in the repository or computed from the architecture
constants used in the code (nca_text/model.py, stage0/run_reviewer_experiments.py); nothing is typed by hand.
Inputs : stage0/stage0_results/reviewer_suite_summary.json  (Hermes factorial, contractive variant, escalation)
         stage0/stage0_results/review_1110/{multibench.json,input_matched_trees.json,stats.json}
Outputs: paper/generated/{numbers_v76c.tex,tab_factorial.tex}
         paper/figures/{fig2_multibench_v76c.pdf,fig3_paired_forest.pdf} (+ .png)
Run after scripts/build_review_tables_1110.py (which writes stats.json).
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "stage0" / "stage0_results"
R11 = RES / "review_1110"
GEN = REPO / "paper" / "generated"
FIG = REPO / "paper" / "figures"
M: dict[str, str] = {}


def put(k, v):
    M[k] = v


def f(x, nd=2):
    return f"{x:.{nd}f}"


def thou(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def build_adjacency(topology: str, V: int = 5) -> np.ndarray:
    """numpy copy of nca_text/model.py::build_adjacency (row-normalised, self-loops, undirected pattern)."""
    A = np.zeros((V, V))
    for i in range(V):
        A[i, i] = 1.0
        if topology == "1d":
            if i > 0:
                A[i, i - 1] = 1.0
            if i < V - 1:
                A[i, i + 1] = 1.0
        elif topology == "star":
            A[0, i] = A[i, 0] = 1.0
        elif topology == "tree" and i > 0:
            p = (i - 1) // 2
            A[p, i] = A[i, p] = 1.0
    return A / A.sum(1, keepdims=True)


def main():
    rss = json.loads((RES / "reviewer_suite_summary.json").read_text())["hermes_factorial_and_contractive"]
    fs = rss["factorial_summary"]
    mb = json.loads((R11 / "multibench.json").read_text())["benchmarks"]
    stats = json.loads((R11 / "stats.json").read_text())

    # ---- architecture constants (code: GraphNCA(obs_c=146, hidden_c=16, n_classes=13, update_hidden=96, seq_len=5)) ----
    D, H, V, C, Dmid = 146, 16, 5, 13, 96
    K = 4
    w1 = Dmid * 3 * (D + H) + Dmid
    w2 = 2 * H * Dmid
    step = K * H
    tool = V * H * C + C
    arg = H * H * 32 + 32
    abst = H + 1
    total = w1 + w2 + step + tool + arg + abst
    assert total == mb["curated"]["models"]["GraphNCA_tree_LS"]["n_params"], total
    assert total + V * V == mb["curated"]["models"]["GraphNCA_meta_LS"]["n_params"]
    for k, v in dict(PWone=w1, PWtwo=w2, PStep=step, PTool=tool, PArg=arg, PAbs=abst, PTotal=total,
                     PTrained=total - arg - abst, PMeta=total + V * V, PKEight=total + 4 * H,
                     PPerc=3 * (D + H), PChan=D + H).items():
        put(k, thou(v))
    assert total + 4 * H == fs["Fact_tree_K8_LS"]["n_params"]
    put("NTabFeat", str(128 + 4 * 14 + 4))
    put("NCellFeat", str(V * D))

    # ---- adjacency spectra (exact for the matrices built in code) ----
    for topo, kk in [("1d", "Chain"), ("star", "Star"), ("tree", "Tree")]:
        ev = np.sort(np.linalg.eigvals(build_adjacency(topo)).real)
        put(f"Eig{kk}Min", f(ev[0], 3))
        put(f"Eig{kk}Second", f(ev[-2], 3))
    At = build_adjacency("tree")
    assert np.allclose(At[1], [0.25, 0.25, 0, 0.25, 0.25]) and np.allclose(At[0], [1 / 3] * 3 + [0, 0])

    # ---- Hermes factorial (reviewer_suite_summary.json) ----
    rows = [("Tree, $K{=}2$", "Fact_tree_K2"), ("Tree, $K{=}4$", "Fact_tree_K4"), ("Tree, $K{=}8$", "Fact_tree_K8"),
            ("Chain, $K{=}4$", "Fact_1d_K4"), ("Star, $K{=}4$", "Fact_star_K4"), ("Learned, $K{=}4$", "Fact_meta_K4"),
            ("Tree, $K{=}4$, carry", "Abl_Tree_K4_Carry"), ("Tree, $K{=}4$, halting", "Abl_Tree_K4_Halt"),
            ("Tree, $K{=}4$, contractive", "Contractive_Tree_K4")]
    t = [r"% AUTO-GENERATED by scripts/build_v76c_extras_1110.py from reviewer_suite_summary.json",
         r"\begin{tabular}{@{}lrcc@{}}", r"\toprule",
         r"Configuration & Params & LS & CW \\", r"\midrule"]
    for name, key in rows:
        ls, cw = fs[f"{key}_LS"], fs[f"{key}_CW"]
        t.append(f"{name} & {thou(ls['n_params'])} & {ls['top1_mean']:.2f} $\\pm$ {ls['top1_sd']:.2f} & "
                 f"{cw['top1_mean']:.2f} $\\pm$ {cw['top1_sd']:.2f} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (GEN / "tab_factorial.tex").write_text("\n".join(t) + "\n")
    for key, kk in [("Fact_tree_K2_LS", "TreeKTwo"), ("Fact_tree_K4_LS", "TreeKFour"), ("Fact_tree_K8_LS", "TreeKEight"),
                    ("Fact_1d_K4_LS", "ChainKFour"), ("Fact_star_K4_LS", "StarKFour"), ("Fact_meta_K4_LS", "MetaKFour"),
                    ("Contractive_Tree_K4_LS", "Contr"), ("Contractive_Tree_K4_CW", "ContrCW"),
                    ("Abl_Tree_K4_Carry_LS", "Carry"), ("Abl_Tree_K4_Halt_LS", "Halt"), ("Fact_tree_K4_CW", "TreeKFourCW")]:
        put(f"F{kk}", f(fs[key]["top1_mean"]))
        put(f"F{kk}Sd", f(fs[key]["top1_sd"]))
        put(f"F{kk}Fone", f(fs[key]["macro_f1_mean"]))
    put("FTreeKFourVal", f(fs["Fact_tree_K4_LS"]["val_top1_mean"]))
    put("FTreeKEightVal", f(fs["Fact_tree_K8_LS"]["val_top1_mean"]))
    g = rss["grokking_curves_3seed"]["Tree_K4_LS"]
    put("CurveFirst", f(g["500"]["val_best_mean"])); put("CurveLast", f(g["3000"]["val_best_mean"]))

    # ---- escalation (K=8 tree model, score = entropy + step norm, beta = 1 in code) ----
    esc = rss["escalation_calibration_3seed"]
    th = {k: [e["thresholds"][k] for e in esc] for k in esc[0]["thresholds"]}
    for k, kk in [("tau_0.76", "SevenSix"), ("tau_0.50", "FiveZero")]:
        put(f"Esc{kk}Rate", f(np.mean([x["escalation_rate_pct"] for x in th[k]]), 1))
        put(f"Esc{kk}Ret", f(np.mean([x["retained_system1_top1_pct"] for x in th[k]])))

    # ---- validation-selected GNCA per benchmark ----
    nice = {"GraphNCA_star_LS": "star", "GraphNCA_1d_LS": "chain", "GraphNCA_meta_LS": "learned", "GraphNCA_tree_LS": "tree"}
    for b, kk in [("curated", "Her"), ("bfcl_e1v2", "Bfcl"), ("toolbench", "Tb"), ("apibank", "Ab")]:
        vs = stats["val_selected"][b]
        put(f"Vs{kk}Model", nice[vs["model"]]); put(f"Vs{kk}Test", f(vs["test"]))
        put(f"N{kk}Val", thou(mb[b]["n"]["val"]))
        put(f"{kk}Meta", f(mb[b]["models"]["GraphNCA_meta_LS"]["top1_mean"]))
        put(f"{kk}Chain", f(mb[b]["models"]["GraphNCA_1d_LS"]["top1_mean"]))
        put(f"{kk}Lin", f(mb[b]["models"]["Linear"]["top1_mean"]))
    put("MlpParams", thou(mb["curated"]["models"]["MLP"]["n_params"]))
    hm = mb["curated"]["models"]
    for m, kk in [("GraphNCA_tree_LS", "TreeLS"), ("GraphNCA_tree_CW", "TreeCW"), ("RandomForest", "Rf"),
                  ("HistGradientBoosting", "Hgb"), ("MLP", "Mlp")]:
        put(f"HerFone{kk}", f(hm[m]["macro_f1_mean"])); put(f"HerTop{kk}", f(hm[m]["top1_mean"]))

    lines = ["% AUTO-GENERATED by scripts/build_v76c_extras_1110.py -- do not edit by hand"]
    lines += [f"\\newcommand{{\\num{k}}}{{{v}}}" for k, v in M.items()]
    (GEN / "numbers_v76c.tex").write_text("\n".join(lines) + "\n")

    figures(mb, stats)
    print(json.dumps(M, indent=0))


def figures(mb, stats):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    imt = json.loads((R11 / "input_matched_trees.json").read_text())["benchmarks"]
    BENCH = [("curated", "Hermes"), ("bfcl_e1v2", "BFCL"), ("toolbench", "ToolBench"), ("apibank", "API-Bank")]
    MODELS = [("RandomForest", "RF", "#E69F00", None, mb), ("RandomForest_packed", "RF$^\\ast$ (cell feat.)", "#E69F00", "////", imt),
              ("HistGradientBoosting", "HGB", "#56B4E9", None, mb), ("HistGradientBoosting_packed", "HGB$^\\ast$ (cell feat.)", "#56B4E9", "////", imt),
              ("MLP", "MLP", "#009E73", None, mb), ("GraphNCA_tree_LS", "GNCA tree", "#D55E00", None, mb),
              ("GraphNCA_star_LS", "GNCA star", "#CC79A7", None, mb)]
    plt.rcParams.update({"font.size": 7, "hatch.linewidth": 0.5, "pdf.fonttype": 42})
    fig, ax = plt.subplots(figsize=(7.0, 2.1))
    x = np.arange(len(BENCH)); w = 0.12; n = len(MODELS)
    for i, (m, lab, c, hatch, src) in enumerate(MODELS):
        if src is imt:
            mu = [imt[b]["models"][m]["test_top1_mean"] for b, _ in BENCH]; sd = [imt[b]["models"][m]["test_top1_sd"] for b, _ in BENCH]
        else:
            mu = [mb[b]["models"][m]["top1_mean"] for b, _ in BENCH]; sd = [mb[b]["models"][m]["top1_sd"] for b, _ in BENCH]
        ax.bar(x + (i - (n - 1) / 2) * w, mu, w * 0.92, yerr=sd, color=c if hatch is None else "white", edgecolor=c,
               hatch=hatch, label=lab, capsize=1.2, error_kw={"lw": 0.5}, linewidth=0.7)
    for xi, (b, _) in zip(x, BENCH):
        ax.hlines(mb[b]["models"]["Majority"]["top1_mean"], xi - n / 2 * w, xi + n / 2 * w, colors="k", linestyles=":", lw=0.8)
    ax.set_xticks(x, [nm for _, nm in BENCH]); ax.set_ylabel("Test top-1 accuracy (%)")
    ax.set_ylim(30, 92); ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=6.5, ncol=7, loc="lower center", bbox_to_anchor=(0.5, 1.0), frameon=False, handlelength=1.4, columnspacing=1.0)
    fig.tight_layout()
    fig.savefig(FIG / "fig2_multibench_v76c.pdf"); fig.savefig(FIG / "fig2_multibench_v76c.png", dpi=200); plt.close(fig)

    # forest plot of paired differences (tree GNCA minus baseline), primary and secondary family
    P, S = stats["paired"], stats["paired_input_matched"]
    comps = [("RandomForest", "RF", P, stats["pooled"]), ("RandomForest_packed", "RF$^\\ast$", S, stats["pooled_input_matched"]),
             ("HistGradientBoosting", "HGB", P, stats["pooled"]), ("HistGradientBoosting_packed", "HGB$^\\ast$", S, stats["pooled_input_matched"]),
             ("MLP", "MLP", P, stats["pooled"])]
    fig, axes = plt.subplots(1, len(comps), figsize=(7.0, 1.9), sharey=True)
    rows = [nm for _, nm in BENCH] + ["Pooled"]
    for ax, (base, lab, fam, pool) in zip(axes, comps):
        for j, (b, nm) in enumerate(BENCH):
            r = fam[f"{b}/GraphNCA_tree_LS-{base}"]
            sig = r["p_holm"] < 0.05
            ax.errorbar(r["diff_pp"], j, xerr=[[r["diff_pp"] - r["ci95"][0]], [r["ci95"][1] - r["diff_pp"]]], fmt="o",
                        ms=3, color="#D55E00" if sig else "#555555", mfc="#D55E00" if sig else "white", lw=0.8, capsize=1.5)
        p = pool[base]
        ax.errorbar(p["estimate_pp"], len(BENCH), xerr=[[p["estimate_pp"] - p["ci95"][0]], [p["ci95"][1] - p["estimate_pp"]]],
                    fmt="D", ms=3.5, color="#0072B2", lw=1.0, capsize=1.5)
        ax.axvline(0, color="k", lw=0.6, ls=":")
        ax.set_title(f"GNCA $-$ {lab}", fontsize=7); ax.set_xlabel("$\\Delta$ top-1 (pp)")
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_yticks(range(len(rows)), rows); axes[0].invert_yaxis()
    fig.tight_layout(w_pad=0.6)
    fig.savefig(FIG / "fig3_paired_forest.pdf"); fig.savefig(FIG / "fig3_paired_forest.png", dpi=200); plt.close(fig)


if __name__ == "__main__":
    main()
