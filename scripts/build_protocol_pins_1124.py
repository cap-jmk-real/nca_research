#!/usr/bin/env python3
"""Write paper/generated/numbers_protocol.tex (dataset pins and OOD aggregate paths).

Sources: data/curated/stats.json, stage0/bfcl_official_runner/PROTOCOL.md (bfcl-eval pin).
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CURATED = REPO / "data" / "curated" / "stats.json"
OUT = REPO / "paper" / "generated" / "numbers_protocol.tex"


def main() -> None:
    stats = json.loads(CURATED.read_text())
    rev = stats["source"]["revision"][:12]
    rev_full = stats["source"]["revision"]
    lines = [
        "% AUTO-GENERATED by scripts/build_protocol_pins_1124.py",
        f"\\newcommand{{\\numHermesDatasetRev}}{{{rev}}}",
        f"\\newcommand{{\\numHermesDatasetRevFull}}{{{rev_full}}}",
        "\\newcommand{\\numHermesDatasetAccess}{2026-11-24}",
        "\\newcommand{\\numBfclEvalVersion}{2026.3.23}",
        "\\newcommand{\\numBfclEvalAccess}{2026-11-14}",
        "\\newcommand{\\numBfclGorillaCommit}{\\texttt{6ea57973c7a6}}",
        "\\newcommand{\\pathOodStats}{\\path{stage0/stage0\\_results/rigour\\_1110/stats\\_rigour.json}}",
        "\\newcommand{\\pathOodPerTurn}{\\path{stage0/stage0\\_results/rigour\\_1110/per\\_turn\\_rigour.npz}}",
        "\\newcommand{\\pathOodSummary}{\\path{stage0/stage0\\_results/rigour\\_1110/rigour\\_summary.json}}",
        "\\newcommand{\\pathOodLatency}{\\path{stage0/stage0\\_results/rigour\\_1110/latency.json}}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()