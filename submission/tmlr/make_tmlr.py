#!/usr/bin/env python3
"""Derive the TMLR-format manuscript (submission/tmlr/main.tex) from paper/main.tex.

Only the preamble, title/author/abstract block, citation commands, appendix
heading and bibliography labels are changed. The scientific body is NOT edited.
Run from anywhere:  python3 submission/tmlr/make_tmlr.py [--accepted]
"""
import re, sys, pathlib

here = pathlib.Path(__file__).resolve().parent
src = (here.parent.parent / "paper" / "main.tex").read_text(encoding="utf-8").split("\n")
accepted = "--accepted" in sys.argv

def find(pred, start=0):
    for i in range(start, len(src)):
        if pred(src[i]):
            return i
    raise SystemExit("anchor not found")

i_doc = find(lambda l: l.startswith(r"\begin{document}"))
i_abs0 = find(lambda l: l.strip().startswith(r"\begin{abstract}"))
i_abs1 = find(lambda l: l.strip().startswith(r"\end{abstract}"))
i_title = find(lambda l: l.startswith(r"\title{"))
abstract_body = [l.strip() for l in src[i_abs0 + 1 : i_abs1]
                 if l.strip() and not l.strip().startswith(r"\vspace")]
abstract_body = [re.sub(r"^\\noindent\s*", "", l) for l in abstract_body]

# keep: theorem envs, colours, listings style from the original preamble
pre = "\n".join(src[:i_title])
keep = []
for blk in (r"\\newtheorem\{[^\n]*\n", r"\\definecolor\{[^\n]*\n"):
    keep += re.findall(blk, pre)
m = re.search(r"\\lstdefinestyle\{leanstyle\}.*?\\lstset\{style=leanstyle\}", pre, re.S)
lst = m.group(0) if m else ""

opt = "accepted" if accepted else ""
head = r"""% Auto-generated by make_tmlr.py from paper/main.tex -- do not edit by hand.
\documentclass[10pt]{article}
\usepackage[@OPT@]{tmlr}
\usepackage[utf8]{inputenc}
\usepackage{amsmath,amssymb,amsfonts,amsthm}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage{graphicx}
\usepackage{xurl}
\usepackage{hyperref}
\usepackage{microtype}
\usepackage{enumitem}
\setlist{topsep=1pt, itemsep=0pt, parsep=1pt, partopsep=0pt}
\usepackage{listings}
\usepackage{color}
\usepackage{xcolor}
\hypersetup{colorlinks=true,linkcolor=blue,citecolor=blue,urlcolor=blue}
\setlength{\tabcolsep}{3pt}% single-column TMLR width (6.5in) vs. original 2-col wide tables
"""
head = head.replace("@OPT@", opt)
head += "".join(keep) + lst + "\n"

title = r"\title{Micro-Routing with Graph Neural Cellular Automata for Sub-Millisecond Agent Tool Selection}"
if accepted:
    author = (r"\author{\name Julian M. Kleber \email julian.m.kleber@gmail.com \\ \addr Independent Researcher, ORCID 0000-0001-5518-0932}")
else:
    author = r"\author{\name Anonymous authors \\ \addr Paper under double-blind review}"
body_start = "\n".join([
    title, author, r"\def\month{MM}  % Insert correct month for camera-ready version",
    r"\def\year{YYYY} % Insert correct year for camera-ready version",
    r"\def\openreview{\url{https://openreview.net/forum?id=XXXX}} % camera-ready only",
    r"\begin{document}", r"\maketitle", r"\begin{abstract}", *abstract_body, r"\end{abstract}",
])

rest = "\n".join(src[i_abs1 + 1 :])
# drop leftover twocolumn wrappers ( \end{@twocolumnfalse} / \vspace{1.2em} / ] )
rest = re.sub(r"^\s*\\vspace\{1\.2em\}\s*\n\s*\\end\{@twocolumnfalse\}\s*\n\]\s*\n", "", rest, count=1, flags=re.M)
# appendix heading used \twocolumn[{...}]
rest = re.sub(r"\\twocolumn\[\{%.*?\}\]\s*", r"\\section*{Supplementary Information: Formal Lean 4 Proofs}\n", rest, count=1, flags=re.S)
# natbib (authoryear) citation commands
rest = re.sub(r"(et al\.|\bal\.)~\\cite\{", r"\1~\\citep{", rest)
rest = rest.replace(r"\cite{", r"\citep{")
# starred floats are plain floats in a single-column layout
rest = rest.replace(r"\begin{figure*}", r"\begin{figure}").replace(r"\end{figure*}", r"\end{figure}")
rest = rest.replace(r"\begin{table*}", r"\begin{table}").replace(r"\end{table*}", r"\end{table}")

# wide tables were laid out for a 7.1in two-column page; TMLR text width is 6.5in
rest = rest.replace(r"\begin{tabular*}{\textwidth}", r"\footnotesize\begin{tabular*}{\textwidth}")

rest = rest.replace(r"{@{\extracolsep{\fill}}lcccc@{}}"+"\n"+r"\toprule"+"\n"+r"\textbf{Model / Architecture Topology}", r"{@{\extracolsep{\fill}}p{0.40\textwidth}cccc@{}}"+"\n"+r"\toprule"+"\n"+r"\textbf{Model / Architecture Topology}")

# authoryear labels for the bibliography
labels = {
 "mordvintsev2020growing": "Mordvintsev et~al.(2020)",
 "pande2023hierarchical": "Pande and Grattarola(2023)",
 "grattarola2021learning": "Grattarola et~al.(2021)",
 "mrowinska2023graph": "Mrowi{\\'n}ska and Deja(2023)",
 "petric2023cellular": "Petric~Mareti{\\'c} et~al.(2023)",
 "etcheverry2026reasoning": "Etcheverry et~al.(2026)",
 "mittal2026textnca": "Mittal et~al.(2026)",
 "lee2026training": "Lee et~al.(2026)",
 "gorilla-bfcl": "Patil et~al.(2024)",
 "sierra2024tau": "Sierra~Research(2024)",
 "singla2026agentweave": "Singla et~al.(2026)",
 "power2022grokking": "Power et~al.(2022)",
 "nanda2023progress": "Nanda et~al.(2023)",
 "li2026fastmodels": "Li(2026)",
}
for k, v in labels.items():
    rest = rest.replace(r"\bibitem{%s}" % k, r"\bibitem[%s]{%s}" % (v, k))

# double-blind: withhold identifying repository / dataset links in the review version
if not accepted:
    W = r"\textit{[link withheld for double-blind review; anonymized mirror to be inserted before submission]}"
    rest = re.sub(r"\\href\{https?://[^}]*cap-jmk[^}]*\}\{\\nolinkurl\{[^}]*\}\}", lambda m: W, rest)
    rest = re.sub(r"\\url\{https?://[^}]*cap-jmk[^}]*\}", lambda m: W, rest)

out = head + body_start + "\n" + rest
(here / ("main_accepted.tex" if accepted else "main.tex")).write_text(out, encoding="utf-8")
print("wrote", here / ("main_accepted.tex" if accepted else "main.tex"))
